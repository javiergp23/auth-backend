const UserSchema = new mongoose.Schema({
    id: { type: Number, required: true, unique: true },
    name: {
        type: String,
        required: true,
    },
    username: {
        type: String,
        required: true,
        unique: true,
    },
    password: {
        type: String,
        required: true,
    },
});

export default mongoose.model("User", UserSchema);